CREATE EXTENSION IF NOT EXISTS vector;

-- A conversation owned by one browser user; the paused workflow lives in workflow_state while it waits for review.
CREATE TABLE chat_threads (
    id                BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    thread_id         VARCHAR(64)  NOT NULL,
    user_id           VARCHAR(100) NOT NULL,
    title             VARCHAR(300) NOT NULL,
    summary           TEXT         NOT NULL DEFAULT '',
    trip_constraints  JSONB        NOT NULL DEFAULT '{}'::jsonb,
    status            VARCHAR(20)  NOT NULL DEFAULT 'IDLE',
    workflow_state    JSONB,
    created_at        TIMESTAMPTZ  NOT NULL,
    updated_at        TIMESTAMPTZ  NOT NULL,
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT pk_chat_threads PRIMARY KEY (id),
    CONSTRAINT uk_chat_threads_thread_id UNIQUE (thread_id),
    CONSTRAINT ck_chat_threads_status CHECK (status IN ('IDLE', 'AWAITING_REVIEW')),
    CONSTRAINT ck_chat_threads_review_state CHECK (status <> 'AWAITING_REVIEW' OR workflow_state IS NOT NULL)
);
CREATE INDEX ix_chat_threads_user_updated ON chat_threads (user_id, updated_at DESC);

CREATE TABLE chat_messages (
    id          BIGINT      GENERATED BY DEFAULT AS IDENTITY,
    thread_pk   BIGINT      NOT NULL,
    role        VARCHAR(20) NOT NULL,
    content     TEXT        NOT NULL,
    meta        JSONB,
    created_at  TIMESTAMPTZ NOT NULL,
    CONSTRAINT pk_chat_messages PRIMARY KEY (id),
    CONSTRAINT fk_chat_messages_thread FOREIGN KEY (thread_pk) REFERENCES chat_threads (id) ON DELETE CASCADE,
    CONSTRAINT ck_chat_messages_role CHECK (role IN ('user', 'assistant'))
);
CREATE INDEX ix_chat_messages_thread ON chat_messages (thread_pk, id);

-- Search-result chunks for hotels, keyed by request, short-lived (see mytripadvision.rag.retention).
CREATE TABLE rag_chunks (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    request_id  VARCHAR(64)  NOT NULL,
    source      VARCHAR(50)  NOT NULL,
    title       TEXT         NOT NULL DEFAULT '',
    url         TEXT         NOT NULL DEFAULT '',
    content     TEXT         NOT NULL,
    embedding   vector(384)  NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT pk_rag_chunks PRIMARY KEY (id)
);
CREATE INDEX ix_rag_chunks_request ON rag_chunks (request_id);
CREATE INDEX ix_rag_chunks_created ON rag_chunks (created_at);

-- Sections of the markdown knowledge base, rebuilt at startup.
CREATE TABLE knowledge_chunks (
    id         BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    source     VARCHAR(200) NOT NULL,
    title      TEXT         NOT NULL,
    heading    TEXT         NOT NULL,
    content    TEXT         NOT NULL,
    embedding  vector(384)  NOT NULL,
    CONSTRAINT pk_knowledge_chunks PRIMARY KEY (id)
);
CREATE INDEX ix_knowledge_chunks_embedding ON knowledge_chunks USING hnsw (embedding vector_cosine_ops);
